"""Finite expression grammar, learned proposals and independent exact certificates."""

import copy
import hashlib
import itertools
from fractions import Fraction as Q
from pathlib import Path

import numpy as np
import torch
from torch import nn

from experiments.learning_progress.model import ProgressR1
from experiments.self_study.algebra import SIZE, check, vector
from experiments.verified_completion.common import digest

WORDS = tuple("".join(p) for n in (1, 2, 3) for p in itertools.product("IM", repeat=n))
DEGREE = 3


def source():
    return hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def canonical(values):
    values = list(map(Q, values))
    first = next((v for v in values if v), None)
    if first is None:
        raise ValueError("The zero identity carries no discovery")
    return tuple(str(v/first) for v in values)


def exact(word, p):
    """Independent rational semantics; composition is written outermost first."""
    result = vector(p)
    if len(word) > 3 or any(c not in "IM" for c in word):
        raise ValueError("Finite integration/time-multiplication grammar required")
    if any(result[DEGREE+1:]):
        raise ValueError("Degree-three input guard")
    for op in reversed(word):
        if result[-1]:
            raise ValueError("Truncation must never masquerade as an identity")
        result = [Q(0)] + [c/(i+1) if op == "I" else c for i, c in enumerate(result[:-1])]
    return result


def learned(owner, word, p):
    result = vector(p)
    if any(result[DEGREE+1:]) or word not in WORDS:
        raise ValueError("Declared polynomial degree and grammar required")
    for op in reversed(word):
        if result[-1]:
            raise ValueError("Unrepresented polynomial tail")
        if op == "I":
            candidate = owner.study_maps["integral"].propose(list(map(str, result)))
            if not check("integral", list(map(str, result)), candidate)["accepted"]:
                raise ValueError("The retained learned primitive requires further acquisition")
            result = list(map(Q, candidate))
        elif op == "M":
            result = [Q(0)]+result[:-1]
        else:
            raise ValueError("Unknown primitive")
    return result


def certify(coefficients):
    coefficient = list(map(Q, canonical(coefficients)))
    residuals = []
    for degree in range(DEGREE+1):
        p = [0]*degree+[1]
        result = [sum(c*exact(w, p)[j] for c, w in zip(coefficient, WORDS, strict=True)) for j in range(SIZE)]
        residuals.append(list(map(str, result)))
    return {"accepted": all(Q(v) == 0 for row in residuals for v in row),
            "scope": "all rational-coefficient polynomials of degree at most three; I anchored at zero; M multiplies by time",
            "argument": "exact coefficient verification on a basis plus linearity of the supplied operators",
            "residuals": residuals, "degree": DEGREE}


def rational_rank(rows):
    matrix = [list(map(Q, r)) for r in rows]
    rank = 0
    for col in range(len(WORDS)):
        pivot = next((i for i in range(rank, len(matrix)) if matrix[i][col]), None)
        if pivot is None:
            continue
        matrix[rank], matrix[pivot] = matrix[pivot], matrix[rank]
        scale = matrix[rank][col]
        matrix[rank] = [v/scale for v in matrix[rank]]
        for i in range(len(matrix)):
            if i != rank:
                scale = matrix[i][col]
                matrix[i] = [a-scale*b for a, b in zip(matrix[i], matrix[rank], strict=True)]
        rank += 1
    return rank


class DiscoveryR1(ProgressR1):
    @classmethod
    def attach(cls, owner):
        if type(owner) is not ProgressR1:
            raise ValueError("Continue the actual learning-progress owner")
        owner.__class__ = cls
        owner.discovery_rules = nn.ParameterDict()
        owner.discovery_policy = nn.Parameter(torch.zeros(3, dtype=torch.float64))
        owner.discovery_source = source()
        return owner

    def export_config(self):
        return {**super().export_config(), "operator_discovery": {"source": self.discovery_source,
                "grammar": list(WORDS), "degree": DEGREE, "rule_ids": sorted(self.discovery_rules)}}


def propose(owner, depth, seed):
    """Construct coefficients from imagined executions, without a formula bank."""
    names = [w for w in WORDS if len(w) == depth]
    rng = np.random.default_rng(seed)
    polynomials = rng.integers(-4, 5, size=(12, DEGREE+1)).tolist()
    values = np.stack([[np.array(learned(owner, w, p), dtype=float) for w in names] for p in polynomials])
    design = torch.tensor(values.transpose(0, 2, 1).reshape(-1, len(names)), dtype=torch.float64)
    # Greedy sparse dependency discovery; fitted coefficients are generated by
    # the learner's imagined executions, not supplied completed equations.
    pivots, proposals = [], []
    for col in range(len(names)):
        if not pivots:
            pivots.append(col)
            continue
        x, y = design[:, pivots], design[:, col]
        coefficient = torch.linalg.lstsq(x, y, driver="gelsd", rcond=1e-10).solution
        if float(torch.linalg.vector_norm(x @ coefficient-y)) > 1e-7:
            pivots.append(col)
            continue
        relation = [Q(0)]*len(WORDS)
        relation[WORDS.index(names[col])] = Q(1)
        for i, value in zip(pivots, coefficient, strict=True):
            relation[WORDS.index(names[i])] = -Q(float(value)).limit_denominator(120)
        proposed = canonical(relation)
        proposals.append({"coefficients": list(proposed), "training_residual": float(torch.linalg.vector_norm(x @ coefficient-y)),
                          "imagined_polynomials": polynomials, "depth": depth})
    return proposals


class Discoveries:
    def __init__(self, owner, saved=None):
        self.owner = owner
        self.records = copy.deepcopy(saved["records"]) if saved else []
        self.events = copy.deepcopy(saved["events"]) if saved else []
        self.rng = torch.Generator().manual_seed(3501)
        if saved:
            self.rng.set_state(torch.tensor(saved["rng"], dtype=torch.uint8))
            with torch.no_grad():
                owner.discovery_policy.copy_(torch.tensor(saved["policy"], dtype=torch.float64))
            for record in self.records:
                if not certify(record["coefficients"])["accepted"]:
                    raise ValueError("A retained relationship lost its exact certificate")
                owner.discovery_rules[record["id"]] = nn.Parameter(torch.tensor(list(map(float, map(Q, record["coefficients"]))), dtype=torch.float64), requires_grad=False)

    def accept(self, proposal):
        coefficient = canonical(proposal["coefficients"])
        certificate = certify(coefficient)
        identifier = digest({"coefficients": coefficient, "scope": certificate["scope"]})
        existing = [r["coefficients"] for r in self.records]
        new = certificate["accepted"] and rational_rank(existing+[coefficient]) > rational_rank(existing)
        if new:
            self.owner.discovery_rules[identifier] = nn.Parameter(torch.tensor(list(map(float, map(Q, coefficient))), dtype=torch.float64), requires_grad=False)
            self.records.append({"id": identifier, "coefficients": list(coefficient), "certificate": certificate,
                                 "origin": "learned coefficients from retained-operator executions", "proposal": proposal})
        return {"new_independent_relation": new, "accepted": certificate["accepted"], "id": identifier,
                "reward": float(new), "certificate": certificate}

    def round(self, sequence):
        probabilities = self.owner.discovery_policy.softmax(-1)
        # Three initial visits ensure a bounded exploration allocation. Later
        # choices are sampled from the retained, reward-updated search policy.
        forced = sequence < 3
        action = sequence if forced else int(torch.multinomial(probabilities.detach(), 1, generator=self.rng))
        proposals = propose(self.owner, action+1, 35100+sequence)
        results = [self.accept(p) for p in proposals]
        reward = sum(r["reward"] for r in results)-.01*(2**(action+1))
        loss = -reward*self.owner.discovery_policy.log_softmax(-1)[action]
        self.owner.discovery_policy.grad = None
        loss.backward()
        with torch.no_grad():
            self.owner.discovery_policy.add_(self.owner.discovery_policy.grad.clamp(-2, 2), alpha=-.05)
        event = {"sequence": sequence, "depth": action+1, "forced_exploration": forced,
                 "probabilities": probabilities.detach().tolist(), "results": results, "reward": reward,
                 "imagined_program_executions": 12*(2**(action+1)), "source": source()}
        self.events.append(event)
        return event

    def snapshot(self):
        return {"records": copy.deepcopy(self.records), "events": copy.deepcopy(self.events),
                "policy": self.owner.discovery_policy.detach().tolist(), "rng": self.rng.get_state().tolist()}

    def alternatives(self, word, p):
        if word not in WORDS:
            raise ValueError("Unknown target program")
        position = WORDS.index(word)
        result = []
        for record in self.records:
            coefficient = [Q(float(v)).limit_denominator(120) for v in self.owner.discovery_rules[record["id"]]]
            if not coefficient[position]:
                continue
            total = [Q(0)]*SIZE
            for i, name in enumerate(WORDS):
                if i != position and coefficient[i]:
                    value = learned(self.owner, name, p)
                    total = [a-coefficient[i]/coefficient[position]*b for a, b in zip(total, value, strict=True)]
            result.append({"rule": record["id"], "result": list(map(str, total)), "scope": record["certificate"]["scope"]})
        return result
